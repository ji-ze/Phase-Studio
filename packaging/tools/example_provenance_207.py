"""Generate clearly labelled synthetic, sanitized provenance examples; no jobs."""
from pathlib import Path
from types import SimpleNamespace
import sys,tempfile,zipfile
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT))
from phase_studio import app as a
from phase_studio.map_quality import MapQualityMetrics
from phase_studio.run_provenance import RunProvenance

out=ROOT/'docs/examples/2.0.7-provenance';out.mkdir(parents=True,exist_ok=True)
with tempfile.TemporaryDirectory() as tmp:
    root=Path(tmp);hkl=root/'synthetic.hkl';hkl.write_text('1 0 0 12 0.1\n')
    cfg=SimpleNamespace(run_id='SYNTHETIC-NO-EXECUTION',work_dir=root,hkl=hkl,cycles=2,
        sharped_model='Synthetic example; no remote request',randomseed='AUTO',damping_factor=0.3,
        reconstruction_mode='Superflip',setting_provenance={'cycles':{'source':'Controlled fixture'}})
    p=RunProvenance(root,cfg)
    p.manifest['limitations'].insert(0,'SYNTHETIC EXAMPLE: fabricated metric values; no scientific program or remote inference executed. Configuration is a minimal example, not a complete runnable project.')
    state=SimpleNamespace(cfg=cfg,observed_hkls={'intensity':hkl},configured_data_mode='intensity')
    for cycle in (1,2):
        directory=root/f'cycle_{cycle:03d}';directory.mkdir()
        (directory/f'cycle_{cycle:03d}_superflip.inflip').write_text('perform CF\nrandomseed AUTO\nfbegin\n1 0 0 12 0.1\nendf\n')
        metrics=MapQualityMetrics(reference_f05=0.5,reference_rmsd=0.2,reference_tp=2,reference_fp=1)
        result=a.CycleResult(cycle,'Synthetic fixture',None,None,None,None,None,None,None,None,
            superflip_quality=metrics,deblur_quality=metrics)
        p.completed_cycle(state,result)
        if cycle==1:p.feedback(dict(source_cycle=1,target_cycle=2,operations=[],next_cycle_reflection_file=str(hkl),written_reflections=1))
        p.cycle_finished(cycle)
    p.finish('complete');p.export_sanitized(root/'example.zip');p.close()
    with zipfile.ZipFile(root/'example.zip') as archive:
        for name in ('run_manifest.json','summary.md','events.jsonl'):(out/name).write_bytes(archive.read(name))
(out/'README.md').write_text('# Synthetic provenance example\n\nGenerated by packaging/tools/example_provenance_207.py using controlled fabricated metrics and a minimal configuration. No Superflip, EDMA or SharpED execution occurred. Local paths and runtime job identifiers are sanitized. This is a format illustration, not a reference scientific result.\n',encoding='utf8')
