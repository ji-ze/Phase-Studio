# Public synthetic ring, not a measured or experimentally validated structure.
cell = engine.gemmi.UnitCell(10, 10, 10, 90, 90, 90)
positions = [(.5 + .14*np.cos(t), .5 + .14*np.sin(t), .5) for t in np.linspace(0,2*np.pi,6,endpoint=False)]
rows = []
for h in range(-5, 6):
    for k in range(-5, 6):
        for l in range(0, 6):
            if (h,k,l)==(0,0,0): continue
            if l==0 and (h<0 or (h==0 and k<0)): continue
            stl = cell.calculate_1_d2(engine.gemmi.Miller(h,k,l)) ** .5 / 2 if hasattr(engine.gemmi,"Miller") else np.sqrt((h*h+k*k+l*l)/100)/2
            factor = sum(np.exp(2j*np.pi*(h*x+k*y+l*z)) for x,y,z in positions)
            intensity = float(abs(factor*6*np.exp(-2*stl*stl))**2)
            rows.append((h,k,l,intensity,max(.1,.04*intensity)))
hkl = DEMO / "tutorial_intensity.hkl"
hkl.write_text("\n".join(f"{h:4d} {k:4d} {l:4d} {v:.8f} {s:.8f}" for h,k,l,v,s in rows)+"\n", encoding="utf8")
cif = DEMO / "tutorial_reference.cif"
