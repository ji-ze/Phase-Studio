"""Offline one-time key provisioning and fail-closed release signing.

Private key format: base64 of the 32-byte Ed25519 seed. The only release secret
is PHASE_STUDIO_UPDATE_SIGNING_KEY. No key is generated by the build workflow.
"""
from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding,PrivateFormat,PublicFormat,NoEncryption
from phase_studio.update_manifest import canonical_manifest,verify_manifest
from phase_studio.update_trust import TRUSTED_KEYS
from phase_studio.update_checker import parse_version

SECRET='PHASE_STUDIO_UPDATE_SIGNING_KEY'


def generate(directory: Path,*,repository: Path=ROOT):
    directory=directory.resolve()
    if directory==repository.resolve() or directory.is_relative_to(repository.resolve()):
        raise ValueError('Private key directory must be outside the repository.')
    if directory.exists() or directory.is_symlink():
        raise ValueError('Key directory must be new; existing keys are never replaced.')
    directory.mkdir(mode=0o700,parents=False)
    if os.name=='nt':
        result=subprocess.run(['whoami','/user','/fo','csv','/nh'],capture_output=True,text=True,check=True)
        sid=next(csv.reader(result.stdout.splitlines()))[1]
        subprocess.run(['icacls',str(directory),'/inheritance:r','/grant:r',f'*{sid}:(OI)(CI)F'],
            stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,check=True)
    key=Ed25519PrivateKey.generate()
    seed=key.private_bytes(Encoding.Raw,PrivateFormat.Raw,NoEncryption())
    public=key.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw)
    metadata={'key_id':hashlib.sha256(public).hexdigest()[:16],'public_key_hex':public.hex()}
    with (directory/'phase-studio-update-signing-key.txt').open('x',encoding='ascii') as output:
        output.write(base64.b64encode(seed).decode('ascii')+'\n')
    (directory/'phase-studio-update-public.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf8')
    return metadata


def pin_public(path: Path,*,destination: Path=ROOT/'phase_studio/update_trust.py'):
    metadata=json.loads(path.read_text(encoding='utf8'))
    public=bytes.fromhex(metadata['public_key_hex'])
    if len(public)!=32 or metadata['key_id']!=hashlib.sha256(public).hexdigest()[:16]:
        raise ValueError('Invalid public key fingerprint.')
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    Ed25519PublicKey.from_public_bytes(public)
    if destination.exists():
        import ast
        tree=ast.parse(destination.read_text(encoding='utf8'))
        # Only an empty initial trust map or the identical provisioned key may
        # be written. Rotation requires an explicitly reviewed source change.
        assignments=[node for node in tree.body if isinstance(node,(ast.Assign,ast.AnnAssign))]
        existing=assignments[-1].value if assignments else None
        empty=isinstance(existing,ast.Dict) and not existing.keys
        if not empty and destination.read_text(encoding='utf8')!=('"""Reviewed public release verification key. No private key material."""\n'
                f'TRUSTED_KEYS = {{{metadata["key_id"]!r}: bytes.fromhex({public.hex()!r})}}\n'):
            raise ValueError('A verification key is already provisioned; rotation requires source review.')
    # Explicit provisioning operation; release builds only read this file.
    destination.write_text('"""Reviewed public release verification key. No private key material."""\n'
        f'TRUSTED_KEYS = {{{metadata["key_id"]!r}: bytes.fromhex({public.hex()!r})}}\n',encoding='utf8')


def asset_names(version):
    return (f'PhaseStudio-{version}-x64.exe',f'PhaseStudio-Jana2020-{version}.zip',
        'SHA256SUMS.txt','release-manifest.json','release-manifest.sig',f'RELEASE_NOTES_{version}.md')


def digest(path):
    with path.open('rb') as source:return hashlib.file_digest(source,'sha256').hexdigest()


def sign_release(directory: Path,version: str,*,keys=None,secret=None):
    if parse_version(version) is None or version!='.'.join(map(str,parse_version(version))):
        raise ValueError('Canonical stable release version required.')
    keys=TRUSTED_KEYS if keys is None else keys
    value=os.environ.get(SECRET,'') if secret is None else secret
    try:
        raw=base64.b64decode(value.strip(),validate=True)
        key=Ed25519PrivateKey.from_private_bytes(raw)
    except (ValueError,TypeError):
        raise ValueError('Signing secret is missing or invalid.') from None
    public=key.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw)
    key_id=hashlib.sha256(public).hexdigest()[:16]
    if keys.get(key_id)!=public:raise ValueError('Signing key does not match the compiled public trust key.')
    names=asset_names(version)
    unexpected={p.name for p in directory.iterdir()}-set(names)
    if unexpected:raise ValueError('Unexpected release asset; refuse publication.')
    if any((directory/name).exists() for name in ('release-manifest.json','release-manifest.sig')):
        raise ValueError('Signed release metadata already exists; do not replace it.')
    if not all((directory/name).is_file() and not (directory/name).is_symlink() for name in (names[0],names[1],names[5])):
        raise ValueError('Both packages and versioned release notes are required.')
    assets=[dict(profile=profile,name=name,size=(directory/name).stat().st_size,sha256=digest(directory/name))
        for profile,name in zip(('standalone-onefile','jana2020-onedir'),names[:2])]
    document=dict(schema=1,application='Phase Studio',repository='ji-ze/Phase-Studio',version=version,
        channel='stable',os='windows',arch='x64',minimum_updater_protocol=1,
        signature_algorithm='Ed25519',key_id=key_id,assets=assets)
    manifest=canonical_manifest(document);signature=key.sign(manifest)
    verify_manifest(manifest,signature,release_version=version,trusted_keys=keys)
    checksums=''.join(f'{item["sha256"]}  {item["name"]}\n' for item in assets)
    (directory/'SHA256SUMS.txt').write_text(checksums,encoding='ascii')
    (directory/'release-manifest.json').write_bytes(manifest)
    (directory/'release-manifest.sig').write_bytes(signature)
    validate_release(directory,version,keys=keys)


def validate_release(directory,version,*,keys=None):
    names=asset_names(version)
    if {p.name for p in directory.iterdir()}!=set(names):raise ValueError('Exactly six release assets required.')
    if any(p.is_symlink() or not p.is_file() for p in directory.iterdir()):raise ValueError('Release assets must be regular files.')
    manifest=verify_manifest((directory/'release-manifest.json').read_bytes(),
        (directory/'release-manifest.sig').read_bytes(),release_version=version,trusted_keys=keys)
    expected=''
    for asset in manifest.assets:
        path=directory/asset.name
        if path.stat().st_size!=asset.size or digest(path)!=asset.sha256:raise ValueError('Release package differs from signed manifest.')
        expected+=f'{asset.sha256}  {asset.name}\n'
    if (directory/'SHA256SUMS.txt').read_text(encoding='ascii')!=expected:raise ValueError('Checksums differ from signed metadata.')
    return manifest


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    commands=parser.add_subparsers(dest='command',required=True)
    generate_parser=commands.add_parser('generate');generate_parser.add_argument('--directory',type=Path,required=True)
    pin=commands.add_parser('pin-public');pin.add_argument('--public-key',type=Path,required=True)
    for command in ('sign','verify'):
        sub=commands.add_parser(command);sub.add_argument('--directory',type=Path,required=True);sub.add_argument('--version',required=True)
    args=parser.parse_args()
    try:
        if args.command=='generate':generate(args.directory);print('Key pair created. Private key was not printed. Protect the private directory.')
        elif args.command=='pin-public':pin_public(args.public_key);print('Public verification key provisioned. Review and commit this public-only change.')
        elif args.command=='sign':sign_release(args.directory,args.version);print('Signed release asset contract verified.')
        else:validate_release(args.directory,args.version);print('Release signature and all package hashes verified.')
    except Exception:
        # Never format exceptions which could contain a signing environment value.
        print('Signing/provisioning failed. Check configuration and the documented asset contract.',file=sys.stderr)
        return 1
    return 0


if __name__=='__main__':raise SystemExit(main())
